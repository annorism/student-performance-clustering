import pandas as pd
import numpy as np

from sklearn.cluster import KMeans
from sklearn.preprocessing import StandardScaler

df = pd.read_csv("Soal latihan pertemuan 11 - Sheet1.csv")

print(df.head())

X = df[['IPK',
        'Kehadiran',
        'Tugas',
        'JamBelajar',
        'Organisasi']]

scaler = StandardScaler()
X_scaled = scaler.fit_transform(X)

kmeans = KMeans(
    n_clusters=3,
    random_state=42,
    n_init=10
)

df['Cluster'] = kmeans.fit_predict(X_scaled)

centroid = pd.DataFrame(
    scaler.inverse_transform(kmeans.cluster_centers_),
    columns=X.columns
)

print("\nCentroid Awal")
print(centroid)

urutan = centroid['IPK'].sort_values(ascending=False).index

mapping = {
    urutan[0]: 0,
    urutan[1]: 1,
    urutan[2]: 2
}

df['Segmentasi'] = df['Cluster'].map(mapping)

nama_cluster = {
    0: 'Mahasiswa Berprestasi Tinggi',
    1: 'Mahasiswa Rata-rata',
    2: 'Mahasiswa Perlu Perhatian'
}

df['Kategori'] = df['Segmentasi'].map(nama_cluster)

print("\nJumlah Mahasiswa Setiap Cluster")
print(df['Kategori'].value_counts())

print("\nData Hasil Clustering")
print(df)

df.to_csv("Hasil_KMeans_Mahasiswa.csv", index=False)

